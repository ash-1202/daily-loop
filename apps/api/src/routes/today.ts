import type { FastifyInstance } from 'fastify';
import { CARDS_PER_DAY, istDate, type TodayResponse } from '@daily-loop/shared';
import { requireUser } from '../app';
import { withTransaction } from '../lib/db-utils';
import { ensureChallenge, getCardRows, progressOf, toCard } from '../services/challenges';

export async function todayRoutes(app: FastifyInstance) {
  /** Today's 5 cards. Answers and explanations appear only on cards the user has answered. */
  app.get('/api/today', async (req): Promise<TodayResponse> => {
    const userId = requireUser(req);
    const { pool, clock } = app.deps;
    const date = istDate(clock());

    // Normally pre-generated by the daily job; built here on demand so a day is never empty.
    const rows = await withTransaction(pool, async (client) => {
      await ensureChallenge(client, date);
      return getCardRows(client, date, userId);
    });

    const progress = progressOf(rows);
    return {
      date,
      cards: rows.map((row) => toCard(row, date)),
      progress,
      completed: progress.answered === CARDS_PER_DAY,
    };
  });
}
